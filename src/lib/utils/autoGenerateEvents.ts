import { eachDayOfInterval, parseISO, format } from 'date-fns';
import type { Trip, TripEvent, MealPreferences } from '@/types';

interface EventToCreate {
  title: string;
  type: 'restaurant' | 'hotel' | 'transport';
  date: string;
  startTime: string;
  endTime: string;
  location: string;
  notes: string;
  cost: number;
  currency: string;
  attachments: string[];
  autoGenerated: boolean;
}

/**
 * Adds minutes to a time string (HH:MM) and returns a new HH:MM string.
 */
function addMinutesToTime(time: string, minutes: number): string {
  const [h, m] = time.split(':').map(Number);
  const totalMinutes = h * 60 + m + minutes;
  const newH = Math.floor(totalMinutes / 60) % 24;
  const newM = totalMinutes % 60;
  return `${String(newH).padStart(2, '0')}:${String(newM).padStart(2, '0')}`;
}

/**
 * Subtracts minutes from a time string (HH:MM) and returns a new HH:MM string.
 */
function subtractMinutesFromTime(time: string, minutes: number): string {
  const [h, m] = time.split(':').map(Number);
  let totalMinutes = h * 60 + m - minutes;
  if (totalMinutes < 0) totalMinutes += 24 * 60;
  const newH = Math.floor(totalMinutes / 60) % 24;
  const newM = totalMinutes % 60;
  return `${String(newH).padStart(2, '0')}:${String(newM).padStart(2, '0')}`;
}

/**
 * Checks if two times are within a given number of minutes of each other.
 */
function timesAreClose(time1: string, time2: string, thresholdMinutes: number): boolean {
  const [h1, m1] = time1.split(':').map(Number);
  const [h2, m2] = time2.split(':').map(Number);
  const diff = Math.abs((h1 * 60 + m1) - (h2 * 60 + m2));
  return diff <= thresholdMinutes;
}

/**
 * Pure function that generates recurring events for a trip based on preferences.
 * Returns an array of event data objects ready to be created.
 */
export function generateRecurringEvents(
  trip: Trip,
  preferences: MealPreferences,
  existingEvents: TripEvent[],
): EventToCreate[] {
  const result: EventToCreate[] = [];
  const currency = trip.budgetCurrency || 'MXN';

  const start = parseISO(trip.startDate);
  const end = parseISO(trip.endDate);
  const days = eachDayOfInterval({ start, end });
  const lastDayStr = format(end, 'yyyy-MM-dd');

  for (const day of days) {
    const dateStr = format(day, 'yyyy-MM-dd');
    const dayEvents = existingEvents.filter((e) => e.date === dateStr);

    // --- Meals ---
    const mealSlots: Array<{ title: string; time: string }> = [
      { title: 'Desayuno', time: preferences.breakfast },
      { title: 'Comida', time: preferences.lunch },
      { title: 'Cena', time: preferences.dinner },
    ];

    for (const slot of mealSlots) {
      const hasExisting = dayEvents.some(
        (e) =>
          e.type === 'restaurant' &&
          e.startTime &&
          timesAreClose(e.startTime, slot.time, 90),
      );

      if (!hasExisting) {
        result.push({
          title: slot.title,
          type: 'restaurant',
          date: dateStr,
          startTime: slot.time,
          endTime: addMinutesToTime(slot.time, 60),
          location: '',
          notes: '',
          cost: preferences.defaultMealCost,
          currency,
          attachments: [],
          autoGenerated: true,
        });
      }
    }

    // --- Hotel (skip last day and days with cruise) ---
    if (dateStr !== lastDayStr) {
      const hasCruise = dayEvents.some((e) => e.type === 'cruise');
      const hasHotel = dayEvents.some((e) => e.type === 'hotel');

      if (!hasCruise && !hasHotel) {
        result.push({
          title: 'Hotel',
          type: 'hotel',
          date: dateStr,
          startTime: '21:00',
          endTime: '08:00',
          location: '',
          notes: '',
          cost: preferences.defaultHotelCost,
          currency,
          attachments: [],
          autoGenerated: true,
        });
      }
    }

    // --- Transfers based on flights ---
    const flightEvents = dayEvents.filter((e) => e.type === 'flight');

    for (const flight of flightEvents) {
      // Flight ARRIVES on this day
      const arrivalTime = flight.endTime || flight.details?.arrivalTime;
      if (arrivalTime && flight.date === dateStr) {
        // Check if this is an arrival (endTime exists or arrivalTime in details)
        const transferTime = addMinutesToTime(arrivalTime, 30);
        const hasTransportNear = dayEvents.some(
          (e) =>
            e.type === 'transport' &&
            e.startTime &&
            timesAreClose(e.startTime, transferTime, 90),
        );

        if (!hasTransportNear) {
          result.push({
            title: 'Traslado Aeropuerto → Hotel',
            type: 'transport',
            date: dateStr,
            startTime: transferTime,
            endTime: addMinutesToTime(transferTime, 60),
            location: '',
            notes: '',
            cost: preferences.defaultTransferCost,
            currency,
            attachments: [],
            autoGenerated: true,
          });
        }
      }

      // Flight DEPARTS on this day
      if (flight.startTime) {
        const transferTime = subtractMinutesFromTime(flight.startTime, 150);
        const hasTransportNear = dayEvents.some(
          (e) =>
            e.type === 'transport' &&
            e.startTime &&
            timesAreClose(e.startTime, transferTime, 90),
        );

        if (!hasTransportNear) {
          result.push({
            title: 'Traslado Hotel → Aeropuerto',
            type: 'transport',
            date: dateStr,
            startTime: transferTime,
            endTime: addMinutesToTime(transferTime, 60),
            location: '',
            notes: '',
            cost: preferences.defaultTransferCost,
            currency,
            attachments: [],
            autoGenerated: true,
          });
        }
      }
    }
  }

  return result;
}
